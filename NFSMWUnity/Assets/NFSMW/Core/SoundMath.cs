    /// <summary>
    /// The dynamic mixer's fixed-point shape maths (EAXSound/Dynamic_Mixer/NFSMixShape.cpp; speed.exe GetCurveOutput
    /// @0x4E42A0): volumes are Q15 (0x7FFF = unity) or hundredths of a dB (0 .. -10000), pitches are cents.
    /// The tables are the game's own (NFSMixShape.cpp g_* arrays).
    /// </summary>
    public static class MixShape
    {
        public const int DwnEqPwr = 0, UpEqPwr = 1, DwnEqPwrSq = 2, UpEqPwrSq = 3, DwnOneMinEqPwr = 4, UpOneMinEqPwr = 5,
            DwnOneMinEqPwrSq = 6, UpOneMinEqPwrSq = 7, DwnLinear = 8, UpLinear = 9;

        /// <summary>GetQ15FromHundredthsdB: 0 dB = 0x7FFF, -6.02 dB per halving, below 50 = 0.</summary>
        public static int Q15FromDb(int db)
        {
            if (db >= 0) return 0x7FFF;
            if (db <= -10000) return 0;
            int shift = db / -0x25A, rem = -(db % 0x25A);
            int r = DbToQ15[0x259 - rem] >> shift;
            return r < 0x32 ? 0 : r;
        }

        /// <summary>GetdBFromQ15 (0 gives -10000).</summary>
        public static int DbFromQ15(int q15)
        {
            if (q15 <= 0) return -10000;
            if (q15 > 0x7FFF) q15 = 0x7FFF;
            int n = 0;
            if ((q15 & 0x4000) == 0)
            {
                bool found = false;
                while (++n != 0x10)
                    if (((0x4000 >> n) & q15) != 0) { found = true; break; }
                if (!found) return -10000;
            }
            int rem = q15 - (0x4000 >> n);
            int db = (n + 1) * -0x25A;
            if (n > 4) rem = (rem << (n - 5)) | Fill[n - 5];
            else rem >>= 5 - n;
            db += Q15ToDb[Math.Min(rem, Q15ToDb.Length - 1)];
            return db < -10000 ? -10000 : db;
        }

        static readonly int[] Fill = { 0x0, 0x1, 0x3, 0x7, 0xF, 0x1F, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF };

        public static float FloatFromDb(int db) => Q15FromDb(db) / 32767f;

        /// <summary>GetCurveOutput: one of the ten mix shapes over a Q15 ratio, as Q15 or (dbOut) hundredths of a dB.</summary>
        public static int Curve(int table, int ratio, bool dbOut)
        {
            ratio = ratio < 0 ? 0 : ratio > 0x7FFF ? 0x7FFF : ratio;
            switch (table)
            {
                case DwnLinear:
                    return dbOut ? DbFromQ15(0x7FFF - ratio) : 0x7FFF - ratio;
                case DwnEqPwr:
                {
                    int rem = ((ratio & 0x1F) << 9) | 0x3FF, i = ratio >> 6;
                    int main = CosTable[i], diff = ((CosTable[i + 1] - main) * rem) >> 15;
                    if (main != 0) main += diff;
                    if (!dbOut) return main;
                    int d = DbFromQ15(main);
                    return d < -0x2580 ? -10000 : d;
                }
                case DwnEqPwrSq:
                    if (dbOut)
                    {
                        int d = Curve(DwnEqPwr, ratio, true) << 1;
                        return d < -0x2580 ? -10000 : d;
                    }
                    else
                    {
                        int o = Curve(DwnEqPwr, ratio, false);
                        return (o * o) >> 15;
                    }
                case DwnOneMinEqPwr:
                {
                    int i = 0x1FF - (ratio >> 6);
                    int o = 0x7FFF - CosTable[i], diff = CosTable[i] - CosTable[i + 1];
                    int rem = ((ratio & 0x1F) << 9) | 0x3FF;
                    int q = o + ((diff * rem) >> 15);
                    if (!dbOut) return q;
                    int d = DbFromQ15(q);
                    return d < -0x2580 ? -10000 : d;
                }
                case DwnOneMinEqPwrSq:
                    if (dbOut)
                    {
                        int d = Curve(DwnOneMinEqPwr, ratio, true) << 1;
                        return d < -0x2580 ? -10000 : d;
                    }
                    else
                    {
                        int o = Curve(DwnOneMinEqPwr, ratio, false);
                        return (o * o) >> 15;
                    }
                case UpOneMinEqPwrSq: return dbOut ? -Curve(DwnOneMinEqPwrSq, ratio, true) : Curve(DwnOneMinEqPwrSq, 0x7FFF - ratio, false);
                case UpEqPwr: return dbOut ? -Curve(DwnEqPwr, ratio, true) : Curve(DwnEqPwr, 0x7FFF - ratio, false);
                case UpOneMinEqPwr: return dbOut ? -Curve(DwnOneMinEqPwr, ratio, true) : Curve(DwnOneMinEqPwr, 0x7FFF - ratio, false);
                case UpEqPwrSq: return dbOut ? -Curve(DwnEqPwrSq, ratio, true) : Curve(DwnEqPwrSq, 0x7FFF - ratio, false);
                case UpLinear: return dbOut ? -Curve(DwnLinear, ratio, true) : Curve(DwnLinear, 0x7FFF - ratio, false);
                default: return 0;
            }
        }

        /// <summary>GetAzimShapeOutput: blends the rolloff of two neighbouring azimuth quadrants (only table 1 is used, as in the game).</summary>
        public static int AzimShape(int table1, int table2, int dx, int dy, int mix)
        {
            int a = Curve(table1, dx, false), b = 0x7FFF;
            if (mix != 0) b = Curve(table1, dy, false);
            int t = mix << 1;
            return ((a * (0x7FFF - t)) >> 15) + ((b * t) >> 15);
        }

        /// <summary>GetPitchMultFromCents.</summary>
        public static float PitchFromCents(int cents)
        {
            float oct = 1f;
            bool neg = cents < 0;
            while (cents > 0x4AF) { cents -= 0x4B0; oct += oct; }
            for (; cents <= -0x4B0; cents += 0x4B0) oct += oct;
            if (!neg) return SemitoneTable[cents / 100] * CentTable[cents % 100] * oct;
            cents = -cents;
            return 1f / SemitoneTable[cents / 100] * (1f / CentTable[cents % 100]) / oct;
        }

        /// <summary>GetIntPitchMultFromCents: 16-bit cents to a pitch multiplier x 4096.</summary>
        public static int IntPitchFromCents(int cents)
        {
            if ((cents & 0x8000) != 0) cents |= unchecked((int)0xFFFF0000);
            return (int)(PitchFromCents(cents) * 4096f);
        }

        /// <summary>GetCentsFromPitchMult.</summary>
        public static int CentsFromPitch(float ratio) =>
            ratio > 1f ? (int)(DbFromQ15((int)(32767f / ratio)) * -1.9931569f) : (int)(DbFromQ15((int)(ratio * 32767f)) * 1.9931569f);

