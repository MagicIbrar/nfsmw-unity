    /// <summary>EAXSndUtil eCURVETYPE.</summary>
    public enum SndCurve { Linear = 0, Parabolic = 1, InvParabolic = 2, Sinusoid = 3, Power = 4, EqPwrSq = 5 }

    /// <summary>cInterpLine (EAXSndUtil.cpp): a value ramping from Start to Finish over Length ms along a curve.</summary>
    public sealed class InterpLine
    {
        float _elapsed, _length, _start, _finish;
        SndCurve _curve;
        public float Value { get; private set; }
        public bool Finished { get; private set; } = true;

        public void Initialize(float start, float finish, int lengthMs, SndCurve curve = SndCurve.Linear)
        {
            _length = lengthMs / 1000f;
            if (_length <= 0) _length = 0.01f;
            _finish = finish;
            _start = start;
            _curve = curve;
            Finished = false;
            Value = start;
            _elapsed = 0;
        }

        /// <summary>Update(t, newFinish): chases a moving target; snaps to it when done.</summary>
        public void Update(float dt, float newFinish)
        {
            _finish = newFinish;
            Update(dt);
            if (Finished) Value = newFinish;
        }

        public void Update(float dt)
        {
            if (Finished) return;
            _elapsed += dt;
            float t = _elapsed;
            if (t > _length) { Finished = true; Value = _finish; return; }
            Value = SndCurves.Eval(_curve, _start, _finish, t / _length);
        }
    }

    /// <summary>cPathLine (EAXSndUtil.cpp): up to five chained InterpLine stages.</summary>
    public sealed class PathLine
    {
        const int MaxStages = 6;
        readonly float[] _len = new float[MaxStages], _start = new float[MaxStages], _finish = new float[MaxStages];
        readonly bool[] _linked = new bool[MaxStages];
        readonly SndCurve[] _curve = new SndCurve[MaxStages];
        float _elapsed;
        int _num, _cur;
        public float Value { get; private set; }
        public bool Finished { get; private set; } = true;

        public void Initialize(float start, float finish, int lengthMs)
        {
            Clear();
            AddStage(start, finish, lengthMs, SndCurve.Linear);
            Value = start;
        }

        public void Clear()
        {
            Value = 0;
            _elapsed = 0;
            _cur = _num = 0;
            for (int i = 0; i < MaxStages; i++) { _len[i] = _finish[i] = _start[i] = 0; _linked[i] = false; _curve[i] = SndCurve.Linear; }
            Finished = false;
        }

        public int AddStage(float start, float finish, int lengthMs, SndCurve curve)
        {
            if (_num == MaxStages - 1) return -1;
            _len[_num] = lengthMs / 1000f;
            if (_len[_num] <= 0) _len[_num] = 0.01f;
            _finish[_num] = finish;
            _start[_num] = start;
            _curve[_num] = curve;
            _linked[_num] = false;
            Finished = false;
            if (_num == 0) Value = _start[0];
            return ++_num;
        }

        /// <summary>AddLinkedStage: a stage that starts where the previous one ends.</summary>
        public int AddLinkedStage(float finish, int lengthMs, SndCurve curve)
        {
            int n = AddStage(_num > 0 ? _finish[_num - 1] : finish, finish, lengthMs, curve);
            if (n > 0) _linked[n - 1] = true;
            return n;
        }

        public void Update(float dt)
        {
            if (Finished || _num == 0) return;
            _elapsed += dt;
            float t = _elapsed;
            if (t > _len[_cur])
            {
                Value = _finish[_cur];
                if (_cur < _num - 1)
                {
                    _elapsed = t - _len[_cur];
                    _cur++;
                    if (_linked[_cur]) _start[_cur] = _finish[_cur - 1];
                }
                else Finished = true;
                return;
            }
            Value = SndCurves.Eval(_curve[_cur], _start[_cur], _finish[_cur], t / _len[_cur]);
        }
    }

    public static class SndCurves
    {
        public static float Eval(SndCurve c, float a, float b, float u)
        {
            float d = b - a;
            switch (c)
            {
                case SndCurve.Parabolic: return d * u * u + a;
                case SndCurve.InvParabolic: return d * (-(u - 1f) * (u - 1f) + 1f) + a;
                case SndCurve.EqPwrSq:
                {
                    int delta = Math.Max(0, Math.Min(0x7FFF, (int)(u * 32767f)));
                    return d * (MixShape.Curve(MixShape.UpEqPwrSq, delta, false) / 32767f) + a;
                }
                default: return d * u + a;
            }
        }

        /// <summary>OldSoundTemplates.hpp smooth(): move toward target by at most delta (up/down).</summary>
        public static float Smooth(float cur, float target, float up, float down) =>
            target > cur + up ? cur + up : target < cur - down ? cur - down : target;

        public static float Smooth(float cur, float target, float delta) => Smooth(cur, target, delta, delta);

        public static int Smooth(int cur, int target, int up, int down) =>
            target > cur + up ? cur + up : target < cur - down ? cur - down : target;

        public static int Smooth(int cur, int target, int delta) => Smooth(cur, target, delta, delta);

        /// <summary>Cubic Bezier over the four rows of an attrib UMath::Matrix4 (UBezierLite::Evaluate; GetValueFromSpline uses y).</summary>
        public static (float x, float y) Bezier(float[] m, int at, float t)
        {
            float u = 1f - t, b0 = u * u * u, b1 = 3f * t * u * u, b2 = 3f * t * t * u, b3 = t * t * t;
            return (b0 * m[at] + b1 * m[at + 4] + b2 * m[at + 8] + b3 * m[at + 12],
                    b0 * m[at + 1] + b1 * m[at + 5] + b2 * m[at + 9] + b3 * m[at + 13]);
        }
    }

    /// <summary>Slope (EAXSndUtil.cpp): clamp-linear map of [Start,Finish] onto [Min,Max].</summary>
    public readonly struct Slope
    {
        readonly float _min, _max, _start, _finish;
        public Slope(float min, float max, float start, float finish)
        {
            _min = min;
            _max = max;
            _start = start;
            _finish = Math.Abs(finish - start) < 1e-6f ? finish + 1e-6f : finish;
        }
        public float Value(float x)
        {
            float s = (x - _start) / (_finish - _start);
            s = s < 0 ? 0 : s > 1 ? 1 : s;
            return s * (_max - _min) + _min;
        }
    }

    /// <summary>Graph (Misc/Table.cpp): piecewise-linear y(x), clamped at the ends.</summary>
    public sealed class Graph
    {
        public readonly float[] X, Y;
        public Graph(int n) { X = new float[n]; Y = new float[n]; }
        public float Value(float x)
        {
            int n = X.Length;
            if (n > 1)
            {
                if (x <= X[0]) return Y[0];
                if (x >= X[n - 1]) return Y[n - 1];
                for (int i = 0; i < n - 1; i++)
                    if (x >= X[i] && x < X[i + 1])
                    {
                        float dy = Y[i + 1] - Y[i], dx = X[i + 1] - X[i];
                        return Math.Abs(dx) > 1e-6f ? (x - X[i]) / dx * dy + Y[i] : dy * 0.5f + Y[i];
                    }
            }
            return n > 0 ? Y[0] : 0;
        }
    }

    /// <summary>Average (Misc/Table.cpp): ring-buffer mean with Record/Flush/Recalculate.</summary>
    public sealed class RunningAverage
    {
        readonly float[] _d;
        int _samples, _slot;
        float _total;
        public float Value { get; private set; }
        public RunningAverage(int slots) { _d = new float[Math.Max(1, slots)]; }

        public void Record(float v)
        {
            if (_samples < _d.Length) _samples++;
            _total += v - _d[_slot];
            _d[_slot] = v;
            _slot = (_slot + 1) % _d.Length;
            Value = _total / _samples;
        }

        public void Flush(float v)
        {
            for (int i = 0; i < _d.Length; i++) _d[i] = v;
            _total = v * _d.Length;
            _samples = _d.Length;
            Value = v;
        }

        public void Recalculate()
        {
            _total = 0;
            foreach (var x in _d) _total += x;
            Value = _total / Math.Max(1, _samples);
        }

        public float Last
        {
            get
            {
                if (_samples == 0) return 0;
                int s = _slot - 1;
                if (s < 0) s = _d.Length - 1;
                return _d[s];
            }
        }
    }
